
import chromadb

from llama_index.core import (
    Document,
    Settings,
    VectorStoreIndex,
)
from llama_index.core.retrievers import VectorIndexRetriever
from llama_index.embeddings.ollama import OllamaEmbedding
from llama_index.vector_stores.chroma import ChromaVectorStore


# --------------------------------------------------
# 1. Configure the embedding model
# --------------------------------------------------

Settings.embed_model = OllamaEmbedding(
    model_name="nomic-embed-text"
)


# --------------------------------------------------
# 2. Create a persistent ChromaDB client
# --------------------------------------------------

chroma_client = chromadb.PersistentClient(
    path="./chroma_data"
)

collection = chroma_client.get_or_create_collection(
    name="retriever_demo"
)

print("ChromaDB collection ready!")


# --------------------------------------------------
# 3. Connect ChromaDB to LlamaIndex
# --------------------------------------------------

vector_store = ChromaVectorStore(
    chroma_collection=collection
)

# Create a LlamaIndex index connected to Chroma.
# This does not load existing Chroma records into memory.
index = VectorStoreIndex.from_vector_store(
    vector_store=vector_store
)


# --------------------------------------------------
# 4. Insert sample documents only when collection is empty
# --------------------------------------------------

if collection.count() == 0:

    documents = [
        Document(
            id_="deadlock-001",
            text="""
            Deadlock occurs when processes wait indefinitely
            for resources. The four necessary conditions are
            mutual exclusion, hold and wait, no preemption,
            and circular wait.
            """,
            metadata={
                "subject": "Operating Systems",
                "topic": "Deadlock",
            },
        ),

        Document(
            id_="binary-search-001",
            text="""
            Binary search is an efficient searching algorithm
            that works on sorted arrays. It repeatedly divides
            the search space into two halves.
            Its time complexity is O(log n).
            """,
            metadata={
                "subject": "DSA",
                "topic": "Binary Search",
            },
        ),

        Document(
            id_="tcp-001",
            text="""
            TCP is a connection-oriented transport layer
            protocol. It provides reliable and ordered
            delivery of data.
            """,
            metadata={
                "subject": "Computer Networks",
                "topic": "TCP",
            },
        ),
    ]

    # Insert documents into the existing Chroma collection.
    # Their embeddings are generated by the configured model.
    index.insert_nodes(
        [
            node
            for node in __import__(
                "llama_index.core.node_parser",
                fromlist=["SentenceSplitter"],
            ).SentenceSplitter(
                chunk_size=300,
                chunk_overlap=30,
            ).get_nodes_from_documents(documents)
        ]
    )

    print("Sample documents inserted into ChromaDB.")

else:
    print(
        f"Using existing collection with "
        f"{collection.count()} stored records."
    )


# --------------------------------------------------
# 5. Create a retriever
# --------------------------------------------------

retriever = VectorIndexRetriever(
    index=index,
    similarity_top_k=3,
)


# --------------------------------------------------
# 6. Retrieve information
# --------------------------------------------------

while True:

    question = input(
        "\nAsk a question (or type 'exit'): "
    )

    if question.strip().lower() == "exit":
        break

    results = retriever.retrieve(question)

    print("\n" + "=" * 65)
    print("CHROMADB RETRIEVAL RESULTS")
    print("=" * 65)

    if not results:
        print("No results retrieved.")
        continue

    for rank, result in enumerate(results, start=1):

        print(f"\nResult {rank}")
        print("-" * 50)

        print("Score:", result.score)
        print("Metadata:", result.node.metadata)
        print("Content:")
        print(result.node.get_content())

